/**
 * In-Browser Project ZIP Archiver
 * Packages workspace files (HTML, CSS, JS, Python, README) into a downloadable .ZIP file.
 */

import JSZip from 'jszip';

export async function exportProjectAsZip(files, projectName = 'ashenai-project') {
  const zip = new JSZip();

  // Add files to zip
  for (const [filename, content] of Object.entries(files)) {
    zip.file(filename, content);
  }

  // Add a helpful README.md
  if (!files['README.md']) {
    zip.file(
      'README.md',
      `# ${projectName}\n\nGenerated by **AshenAI Code Workspace** on ${new Date().toLocaleString()}.\n\n### How to Run:\nOpen \`index.html\` in any web browser to view the application!\n`
    );
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${projectName}-${new Date().toISOString().slice(0, 10)}.zip`;
  a.click();
  URL.revokeObjectURL(url);
}
